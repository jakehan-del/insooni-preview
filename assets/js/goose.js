/* ══════════════════════════════════════════════════════════════════
   거위 — 이 사이트의 캐릭터.  window.INSOONI_GOOSE(...)

   「거위의 꿈」이 어머니의 대표곡이라 거위는 장식이 아니라 얼굴이다.
   그래서 성체 실루엣이 아니라 아기 비율로 그린다.

   고르는 과정 (다섯 안을 전부 렌더해 나란히 놓고 봤다)
     기품 / 올려보기 / 깃털 / 한몸짓 / 두마리 중 「깃털」을 골랐다.
     44px 무리 크기에서 날개와 목이 살아 있는 것이 이것 하나뿐이었다.
     나머지는 갈매기 같은 작은 획이거나 오리 떼로 보였다.

   그 뒤 세 번 고쳤다
     v2  원안은 드러난 목이 머리의 1.22배뿐이라 '통통한 비둘기'로 읽혔다
         (원작자가 스스로 적어 둔 미해결 결함). 목을 8.4단위 뽑고
         밑동 17.3 → 끝 6.6으로 좁혔다. 앞뒤 곡선은 반대 방향으로 휜다 —
         같은 방향으로 휘면 목이 아니라 굽은 관이 된다.
     v3  아기 비율. 머리 지름 17.2 → 21.2 (몸 높이의 0.65배 → 0.82배),
         부리 13.4 → 9.0, 눈을 머리 중심선 '아래'로, 몸통을 통통하게.
         목은 8.4 → 5.5 로 절반만 남겼다 — 목은 거위로 읽히는 유일한
         근거라 없앨 수 없고, 잃은 귀여움은 머리를 키워 되찾았다.
     v3b 몸을 키우면서 가슴선의 두 끝이 실루엣 안쪽으로 들어가 배에 뜬
         흠집이 됐다. 윤곽 밖으로 다시 빼서 clip 이 물게 했다.
         (한가운데서 시작해 한가운데서 끝나는 선은 형태가 아니라 흠집이다)

   검사 통과: save/restore 6:6 · ES5 · 색 두 가지 · 알파 곱셈 · NaN 방어
   ══════════════════════════════════════════════════════════════════ */
/* ------------------------------------------------------------------
   아기거위 — 실루엣이 아니라 형태.  (적대적 검토 후 수정본)

   색은 둘뿐이다. 몸 #F3EFE7, 배경 #070707.
   날개깃·꼬리깃·가슴선은 세 번째 색이 아니라 배경색으로 몸을 '뚫은' 자리다.
   ★ 그러려면 뚫는 획은 alpha 를 타면 안 된다. 반투명한 몸 위에 반투명한
     배경색을 얹으면 구멍이 아니라 회색 얼룩이 된다(alpha=0.34 에서
     몸 87, 구멍 60, 하늘 7 — 셋째 색). 그래서 몸은 alpha 로 칠하고
     뚫는 자리는 호출자 알파(base)로 온전히 얹는다. 결과적으로 멀리 있는
     흐린 거위일수록 눈이 또렷해진다. 그게 싫으면 alpha 낮을 때 lod 를
     내려라 — 그건 설계 결정이지 버그가 아니다.

   sz    = 부리 끝에서 꼬리 끝까지의 가로 길이(px). 20 / 44~50 / 300.
   ※ v3 — 아기 비율. 목은 거위로 읽히는 유일한 근거라 절반만 남기고(8.4→5.5),
     잃은 귀여움은 머리를 키워 되찾았다(지름 17.2→21.2). 설계 폭 93.9.
   원점  = 몸통 중심(몸통 bbox 중심에서 1.2 단위 안쪽). 빛무리·수면 반사 기준.
   sx,sy = 좌우 반전(음수)과 부피 보존 스쿼시. tilt = 진행 방향.
           ※ rotate 가 scale 보다 먼저다. sx<0 인 개체는 호출자가 tilt 를
             뒤집어 넘겨야 진행 방향이 맞는다.

   ------------------------------------------------------------------
   크기에 따라 선을 줄인다.
     단계 0 (sz < 32)   실루엣만. 눈도 없다.
     단계 1 (32~71)     눈 + 날개깃 1                     ← 주역 크기
     단계 2 (72~149)    + 날개깃 1 + 어깨선 + 꼬리깃 1
     단계 3 (150~)      + 날개깃 1 + 꼬리깃 1 + 가슴선 + 부리선 + 눈빛
   단계는 sz 만 보고 정한다(스쿼시로 판정하면 문턱에서 깜빡인다).
   다만 sz 를 부드럽게 키우면 문턱에서 선이 한꺼번에 튀어나온다 —
   확대 연출을 넣을 거면 히스테리시스를 호출부에서 걸어라.

   [고친 것]
   1) 꼬리깃이 꼬리 윤곽과 나란히·0.05단위 거리로 지나가 윗변을 통째로
      갉아먹고 머리카락 두께의 살만 남기던 것 → 뿌리에서 뒷전으로 부챗살처럼
      다시 그었다(윤곽 여유 1.24~1.48, 반굵기 0.93).
   2) 눈: 지름이 머리폭의 24.4% (실제 거위 10~13%) 였고 입선보다 2단위
      아래, 부리 뿌리와는 0.1단위 겹쳐 있었다 → 16.7%, 입선 위, 여백 1.6.
   3) 눈빛이 부리 쪽으로 고정 오프셋이라 sx<0 이면 뒤통수 쪽에서 빛났다
      → 동공 바로 위(좌우 반전 불변)로.
   4) 목 앞아래선이 몸통 윤곽 밖으로 나갔다 되들어와 가슴에 V 홈이
      패었다(y=-5 에서 1.4단위) → 몸통 최대폭에 접선으로 붙였다.
   5) 부리 끝이 마지막 2단위에서 4.27→1.64 로 무너져 첨점이 됐다
      ("뾰족하면 참새가 된다"는 자기 주석 위반) → 손톱(nail)으로 막았다.
   6) globalAlpha 를 덮어써서 호출자가 걸어 둔 페이드를 무시했다 → 곱한다.
   7) 부리선만 클립 없이 그어져 있었다(지금 좌표로는 새지 않지만
      한 번만 건드리면 하늘에 흠집) → 클립 안으로.

   [안 고친 것 — 설계 결정이 필요하다]
   드러난 목이 21.9단위, 머리(18)의 1.22배뿐이고 두께가 16.6단위로
   머리 높이(16.6)와 같다. 날고 있는 거위는 목이 머리의 2~3배, 두께는
   머리의 0.5~0.65배다. 그래서 이 새는 거위가 아니라 통통한 비둘기로
   읽힌다. 「거위의 꿈」의 무게는 '날 수 없게 생긴 무거운 새'에서 오므로
   이건 치명적이다. 다만 목을 늘리면 부리 끝~꼬리 끝 93 단위가 흔들려
   전체 비례를 다시 잡아야 한다 — 검토자가 손댈 자리가 아니다.
   ------------------------------------------------------------------ */
function goose(c, x, y, sz, flap, sx, sy, tilt, alpha) {
  var INK = "#F3EFE7";
  var BG = "#070707";
  var TAU = Math.PI * 2;
  var lod, k, w, cut, er, ex, ey, tx, ty, wx, wy, base;

  /* 인자 하나가 undefined 여도 거위 한 마리가 통째로 사라진다. 막아 둔다.
     NaN 은 오류도 없이 조용히 그림을 지운다 — 소리 없는 실패라 더 나쁘다 */
  if (!(sz > 0)) return;
  if (!isFinite(flap)) flap = 0;
  if (sx == null || !isFinite(sx) || sx === 0) sx = 1;
  if (sy == null || !isFinite(sy) || sy === 0) sy = 1;
  if (tilt == null || !isFinite(tilt)) tilt = 0;
  if (alpha == null || !isFinite(alpha)) alpha = 1;
  if (alpha <= 0) return;
  if (alpha > 1) alpha = 1;

  lod = sz < 32 ? 0 : (sz < 72 ? 1 : (sz < 150 ? 2 : 3));
  /* 수면 반사(sy 음수)는 한 단계 내린다 */
  if (sy < 0 && lod > 1) lod = 1;

  k = sz / 93.9;                                /* 설계 단위 93.9 = 부리 끝(53.4)~꼬리 끝(-40.5) */
  w = Math.sin(flap);                           /* -1 내려침 … +1 올려침 */

  /* 뚫는 선의 굵기는 화면 픽셀로 정하고 로컬 단위로 되돌린다 */
  cut = Math.max(1.2, Math.min(sz * 0.020, 9)) / k;

  /* 날개 끝. 내려쳐도 등선 위로 11.7 단위는 남는다 */
  tx = -2 - w * 7;
  ty = -36 - w * 10;

  /* 손목(수근관절) — 깃이 갈라지는 곳 */
  wx = 13 + (tx - 13) * 0.30;
  wy = -6 + (ty + 6) * 0.30;

  /* 깃선 한 줄. 손목에서 뒷전 너머로 뻗다가 clip 에 잘린다 */
  function quill(u) {
    var gx = tx + (-8 - tx) * u, gy = ty + (-8 - ty) * u;
    var vx = gx - wx, vy = gy - wy;
    c.beginPath();
    c.moveTo(wx + vx * 0.10, wy + vy * 0.10);
    c.quadraticCurveTo(wx + vx * 1.0 - vy * 0.07, wy + vy * 1.0 + vx * 0.07,
                       wx + vx * 1.9, wy + vy * 1.9);
    c.stroke();
  }
  /* 뚫을 때 / 칠할 때. 알파가 다르다 — 위 주석 참고 */
  function punch() { c.globalAlpha = base; c.strokeStyle = BG; c.fillStyle = BG; }
  function ink() { c.globalAlpha = base * alpha; c.fillStyle = INK; }

  c.save();
  base = c.globalAlpha;                         /* 호출자가 이미 걸어 둔 페이드를 살린다 */
  c.translate(x, y);
  c.rotate(tilt);
  c.scale(k * sx, k * sy);
  c.lineJoin = "round";
  c.lineCap = "round";

  /* ---------- 꼬리 — 몸통보다 먼저. 몸의 끝맺음이지 붙인 깃발이 아니다 ---------- */
  ink();
  c.beginPath();
  c.moveTo(-19, -7.5);
  c.bezierCurveTo(-27, -9.5, -34, -10.8, -40.5, -10.6);
  c.bezierCurveTo(-37, -6.8, -33, -3.2, -28.5, 0.2);
  c.bezierCurveTo(-25, -1.6, -21.5, -3.6, -18, -5.2);
  c.closePath();
  c.fill();

  if (lod >= 2) {
    c.save();
    c.clip();                       /* 꼬리깃이 밖으로 새면 하늘에 흠집이 난다 */
    punch();
    c.lineWidth = cut;
    /* 꽁지 뿌리 한 점에서 부챗살로. 시작점은 몸통이 덮어 감추고
       끝점은 뒷전 너머라 clip 이 깃 끝으로 잘라 준다.
       윤곽과 나란히 긋지 않는다 — 나란하면 윤곽만 갉아먹고 사라진다 */
    c.beginPath(); c.moveTo(-17.5, -6.0); c.lineTo(-40.5, -6.7); c.stroke();
    if (lod >= 3) {
      c.beginPath(); c.moveTo(-17.5, -6.0); c.lineTo(-37.0, -2.8); c.stroke();
    }
    c.restore();
  }

  /* ---------- 몸통 — 공이 아니다. 등이 서고 가슴이 나오고 뒤로 좁아진다 ---------- */
  ink();
  c.beginPath();
  c.moveTo(-22, -3);
  c.bezierCurveTo(-18.5, -12.0, -8, -16.2, 3, -15.6);
  c.bezierCurveTo(12.5, -15.1, 20, -10, 22, -2);
  c.bezierCurveTo(23.8, 5.6, 14.5, 13.4, 1.5, 14.0);
  c.bezierCurveTo(-9.5, 14.6, -19.0, 10.4, -23.0, 2.8);
  c.bezierCurveTo(-24.6, 0.1, -24.4, -1, -22, -3);
  c.closePath();
  c.fill();

  if (lod >= 3) {
    c.save();
    c.clip();
    punch();
    c.lineWidth = cut;
    /* 가슴선 — 양 끝을 윤곽 밖에서 시작하고 끝내서 clip 이 실루엣에 물려 준다.
       몸 한가운데서 시작해 한가운데서 끝나는 선은 형태가 아니라 흠집이다 */
    c.beginPath();
    /* v3: 몸을 통통하게 키우면서 이 선의 두 끝이 실루엣 '안쪽'으로 들어가
       배에 뜬 흠집이 됐다. 다시 윤곽 밖으로 빼서 clip 이 물게 한다.
       시작 (24.5,-12) · 끝 (-0.5,17) — 둘 다 새 몸통 바깥이다. */
    c.moveTo(24.5, -12);
    c.bezierCurveTo(21.0, -2, 15.0, 7.5, -0.5, 17);
    c.stroke();
    c.restore();
  }

  /* ---------- 목 — 짧고 굵되 한 번은 휜다.
       앞아래 끝을 몸통 최대폭(21,-2)에 접선으로 붙인다. 예전처럼 몸통 밖으로
       나갔다 되들어오면 가슴에 V 홈이 팬다 ---------- */
  ink();
  c.beginPath();
  c.moveTo(6, -10);
  /* 뒷목 — 한 번 휘어 오른다. 곧게 뽑으면 백조가 되고, 안 뽑으면 비둘기가 된다 */
  /* 뒷목은 살짝 볼록, 앞목은 살짝 오목 — 두 선이 같은 방향으로 휘면
     목이 아니라 굽은 관이 된다. 반대로 휘어야 목으로 읽힌다 */
  c.bezierCurveTo(10.0, -18.5, 18.5, -29.8, 28.6, -35.8);
  /* 목 꼭대기 폭 7.4 단위. 아기는 목도 굵다 — 6.6 은 어른 비율이었다.
     밑동 17.3 에서 여기까지만 좁아진다 */
  c.lineTo(34.6, -33.5);
  c.bezierCurveTo(31.5, -24.5, 25.0, -11.5, 20.6, -0.8);
  c.closePath();
  c.fill();

  /* ---------- 머리 ----------
     목 꼭대기(33.05,-36.8)에서 8.4 단위 더 나가 앉는다.
     예전에는 5.1 밖에 안 떨어져 머리가 목을 덮었고, 그래서 목이 없어 보였다.
     다만 완전히 떼면 이어붙인 티가 난다 — 2 단위쯤 겹치게 둔다.
     v3: 지름을 17.2 → 21.2 로 키웠다. 몸 높이(26)의 0.65배였던 것이 0.82배가 된다.
     아기 비율은 0.8~0.9 다. 이 한 줄이 귀여움의 절반이다. */
  c.beginPath();
  c.ellipse(36.9, -39.3, 10.6, 9.9, -0.20, 0, TAU);
  c.fill();

  /* ---------- 부리 — 짧고 뭉툭하게. 끝은 첨점이 아니라 손톱으로 막는다.
       뾰족하면 거위가 아니라 참새가 된다 ---------- */
  c.beginPath();
  c.moveTo(43.8, -43.6);
  c.bezierCurveTo(48.6, -44.2, 51.9, -43.4, 52.9, -41.9);
  c.bezierCurveTo(53.4, -41.2, 53.4, -40.2, 52.9, -39.6);
  c.bezierCurveTo(51.9, -38.3, 48.6, -37.6, 43.8, -37.2);
  c.closePath();
  c.fill();

  if (lod >= 3) {
    c.save();
    c.clip();                       /* 클립 없는 뚫기는 하나도 두지 않는다 */
    punch();
    c.lineWidth = cut * 0.55;
    c.beginPath();
    c.moveTo(41.5, -34.6);
    c.bezierCurveTo(45, -34.8, 48.5, -34.7, 51.6, -34.4);
    c.stroke();
    c.restore();
  }

  /* ---------- 눈 — 입선 위, 부리 뿌리에서 1.6 단위 물러나 앉는다.
       지름은 머리폭의 16.7%. 24% 는 눈이 아니라 캐릭터 상품이다.
       작아질 때만 화면 0.85px 바닥으로 버틴다 ---------- */
  if (lod >= 1) {
    /* 큰 크기에서는 눈을 더 줄인다. 44px 에서 또렷한 눈이 300px 에서는 상품 캐릭터가 된다 */
    er = (lod >= 3 ? 1.62 : 1.75) * (sz >= 150 ? 1 : 1.05);
    er = Math.max(er, 0.85 / k);
    /* 머리 중심(36.9,-39.3)보다 아래·앞. 아기 얼굴은 눈이 낮게 붙는다.
       중심선 위에 두면 같은 크기라도 어른 새로 읽힌다 */
    ex = 40.4; ey = -38.9;
    punch();
    c.beginPath(); c.arc(ex, ey, er, 0, TAU); c.fill();
    if (lod >= 3) {
      /* 눈빛은 동공 바로 위. 앞뒤로 치우치면 좌우 반전에서 빛이 뒤통수로 간다 */
      ink();
      c.beginPath(); c.arc(ex, ey - er * 0.42, er * 0.30, 0, TAU); c.fill();
    }
  }

  /* ---------- 날개 — 마지막. 몸 위에 얹힌다 ---------- */
  c.save();
  c.translate(2, -7); c.rotate(-w * 0.12); c.translate(-2, 7);
  ink();
  c.beginPath();
  c.moveTo(-8, -8);
  c.bezierCurveTo(-9.5, -17 - w * 4, -11 - w * 4, -28 - w * 7, tx, ty);
  c.bezierCurveTo(tx + 8 - w * 2, ty + 3.5, 10 - w, -21 - w * 4, 13, -6);
  c.bezierCurveTo(7, -4.2, -2, -4.6, -8, -8);
  c.closePath();
  c.fill();

  if (lod >= 1) {
    c.save();
    c.clip();                       /* 깃선이 날개 밖으로 새면 몸통이 파인다 */
    punch();
    c.lineWidth = cut;
    quill(0.45);                    /* 한 줄만 남긴다면 이것 */
    if (lod >= 2) {
      quill(0.18);
      /* 어깨선 — 날개 뿌리를 그대로 따라간다 */
      c.beginPath();
      c.moveTo(14.2, -6.2);
      c.bezierCurveTo(7, -4.6, -2, -5.0, -9.2, -9.0);
      c.stroke();
    }
    if (lod >= 3) { quill(0.72); }
    c.restore();
  }
  c.restore();

  c.restore();
}
