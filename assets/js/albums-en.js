/* 정규 1~18집의 발매 정보는 형식이 일정해 규칙으로 영문을 만든다.
   "정규 7집 · 발매 1987. 4. · Jigu · 11곡 수록"
   → "Studio album no.7 · released April 1987 · Jigu · 11 tracks" */
window.regCreditsEN = function (ko) {
  if (!ko) return "";
  var MON = ["January", "February", "March", "April", "May", "June",
             "July", "August", "September", "October", "November", "December"];
  return ko.split(" · ").map(function (part) {
    var m = part.match(/^정규\s*(\d+)집$/);
    if (m) return "Studio album no." + m[1];
    m = part.match(/^발매\s*(\d{4})\.\s*(\d{1,2})\.\s*(\d{1,2})\.?$/);
    if (m) return "released " + m[3] + " " + MON[+m[2] - 1] + " " + m[1];
    m = part.match(/^발매\s*(\d{4})\.\s*(\d{1,2})\.?$/);
    if (m) return "released " + MON[+m[2] - 1] + " " + m[1];
    m = part.match(/^발매\s*(\d{4})$/);
    if (m) return "released " + m[1];
    m = part.match(/^(\d+)곡 수록$/);
    if (m) return m[1] + " tracks";
    if (part === "현대음향") return "Hyundai Sound";
    if (part === "세원음반") return "Sewon Records";
    if (part === "지앤지프로덕션(주)") return "GNG Production";
    return part;                      /* 레이블명은 고유명사 그대로 */
  }).join(" · ");
};
